// Deep type that replaces literal strings with `string` so other locales can use their own values
type DeepStringify<T> = {
  [K in keyof T]: T[K] extends string
    ? string
    : T[K] extends readonly { emoji: string; text: string }[]
    ? readonly { emoji: string; text: string }[]
    : DeepStringify<T[K]>;
};

export type TranslationKeys = DeepStringify<typeof ru>;
